#!/usr/bin/env node
/* GLANCELESS REGISTER GATE. It fails closed and accepts no flags.
 * The page measures rendered output, so this gate checks the same boundary: the tree cannot
 * drift from the package evidence, its fixed accent, its captured program output, or its deploy.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fail = (s) => { console.error('FAIL  ' + s); process.exitCode = 1; };
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const files = [];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', '.next', '.open-next', '.wrangler', '.git', 'review', 'vendor'].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else files.push(p);
  }
}
walk(ROOT);
const own = files.filter((p) => /.(ts|tsx|mjs|js|css|json|md|svg|sh)$/.test(p) && !p.endsWith('check-register.mjs'));
const text = own.filter((p) => !p.endsWith('/AGENTS.md') && !p.endsWith('/CLAUDE.md')).map((p) => [p, fs.readFileSync(p, 'utf8')]);
const badDash = text.flatMap(([p, s]) => [...s].filter((c) => ['—', '–', '−'].includes(c)).map(() => path.relative(ROOT, p)));
if (badDash.length) fail('wide dash in ' + [...new Set(badDash)].join(', '));
const product = read('src/lib/product.ts');
const css = read('src/app/globals.css');
const expectedHomes = ['src/app/globals.css', 'src/app/icon.svg', 'src/app/og-card/route.tsx', 'src/lib/product.ts', 'public/favicon.svg', 'README.md'];
const accentFiles = text.filter(([, s]) => /#CD9AE6/i.test(s)).map(([p]) => path.relative(ROOT, p));
if (accentFiles.some((p) => !expectedHomes.includes(p))) fail('accent appears outside declared homes: ' + accentFiles.join(', '));
if (!css.includes('--accent:#CD9AE6') || !css.includes('--accent-hover:#E1ACFA')) fail('accent or hover is not declared');
if (!css.includes('The estate ring is full')) fail('ring register is missing');
if (!read('src/components/SmoothScroll.tsx').includes('allowNestedScroll: true')) fail('Lenis nested scroll clause is missing from the register');
if (!product.includes("host: 'glanceless.thecompound.tech'") || !product.includes("repo: 'https://github.com/kyisaiah47/glanceless'")) fail('host or repo is not declared once in product.ts');
const sourceRows = [...product.matchAll(/id: '([^']+)'[\s\S]*?quote: '[\s\S]*?'[\s\S]*?url: 'https?:\/\/[^']+'[\s\S]*?read_at: '\d{4}-\d{2}-\d{2}'/g)];
if (sourceRows.length < 8) fail('fewer than 8 source rows carry quote, url and read date');
if (!read('src/app/page.tsx').includes('SOURCES.map')) fail('the source register is not rendered');
if (read('src/app/page.tsx').includes('width="100%"')) fail('a picture takes the full reading column');
if (!read('src/components/SmoothScroll.tsx').includes("prefers-reduced-motion") || !read('src/components/SmoothScroll.tsx').includes('allowNestedScroll: true')) fail('Lenis does not yield to reduced motion and nested scroll');
if (!read('scripts/deploy.sh').includes('deploy_gate "glanceless-site"') || read('scripts/deploy.sh').indexOf('deploy_gate') > read('scripts/deploy.sh').indexOf('npm run check')) fail('deploy gate does not run before check');
if (!read('scripts/deploy.sh').includes('node scripts/verify-cf.mjs')) fail('deploy does not end with verify-cf');
if (!read('scripts/verify-cf.mjs').includes("'/llms.txt'")) fail('verify routes do not cover the crawl surface');
if (!read('scripts/layout-gate.mjs').includes("const ROUTES = ['/'];")) fail('layout routes include a page this app does not have');
if (!read('src/lib/measured.ts').includes('GENERATED by scripts/capture.mjs')) fail('captured output is not generated');
if (!read('src/app/layout.tsx').includes('thecompound.tech/#organization')) fail('publisher does not reference the Compound Labs organization node');
if (!read('src/app/page.tsx').includes('Built by') || !read('src/app/page.tsx').includes('hello@thecompound.tech')) fail('studio credit is incomplete');
if (process.exitCode) process.exit(1);
console.log('check-register: 12 clauses hold. Nothing found that permits a bypass.');
